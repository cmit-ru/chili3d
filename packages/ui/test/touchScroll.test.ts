/**
 * Прокрутка панелей пальцем и жест камеры делят одно свойство — `touch-action`
 * (B-316). Пока запрет стоял у `html` и `body`, он по цепочке предков доставал и
 * во вложенные блоки: дерево модели, свойства, лента инструментов, содержимое
 * плавающего окна и панель урока на планшете не листались вовсе. Правило страницы
 * сужено до панорамирования, а запрет переехал туда, где он и нужен, — на сцену.
 *
 * Разъехаться эти две половины могут молча: сузить страницу и забыть про сцену —
 * значит потерять вращение камеры, единственное, что на планшете уже работало;
 * вернуть странице `none` — значит вернуть непрокручиваемые панели. Обе живут в
 * CSS, браузера в наборе нет, поэтому читаем файлы текстом, как в
 * `treeMoveButtons.test.ts`. Комментарии срезаем: в них те же слова, что в правилах.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, test } from "@rstest/core";

const безКомментариев = (файл: string) =>
    readFileSync(path.resolve(__dirname, файл), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

const СТРАНИЦА = безКомментариев("../../../public/index.css");
const СЦЕНА = безКомментариев("../src/viewport/viewport.module.css");

/** Тело правила — до первой закрывающей скобки: вложенных блоков в обоих нет. */
const правило = (css: string, селектор: string) => new RegExp(`${селектор}\\s*\\{([^}]*)\\}`).exec(css)?.[1];

describe("пальцем листаются панели, но не сцена", () => {
    const страница = правило(СТРАНИЦА, "html,\\s*body");

    test("страница отдаёт панорамирование браузеру — иначе панели не листаются", () => {
        expect(страница).toBeTruthy();
        expect(страница).toMatch(/touch-action:\s*pan-x pan-y/);
    });

    test("страница по-прежнему не масштабируется щипком и двойным касанием", () => {
        // `manipulation`, `pinch-zoom` и `auto` разрешили бы масштаб: ребёнок увеличил
        // бы редактор вдвое и не понял, куда делась половина инструментов.
        expect(страница).not.toMatch(/touch-action:[^;]*(auto|manipulation|pinch-zoom)/);
    });

    test("сцена держит жест у себя — камеру крутит редактор, а не браузер", () => {
        expect(правило(СЦЕНА, "\\.root")).toMatch(/touch-action:\s*none/);
    });
});
