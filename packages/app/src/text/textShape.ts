// Контуры букв → объёмная надпись.
//
// Путь тот же, которым идут все браузерные CAD на OpenCascade (replicad,
// CascadeStudio): шрифт разбирает opentype.js, а геометрию строит ядро —
// отрезок и кривая Безье → замкнутый контур → грань → выдавливание.
// Родной текст OCCT (Font_BRepFont) здесь не годится: он требует FreeType,
// которого в нашей сборке ядра нет, а в браузере всё равно нет системных
// шрифтов и файл пришлось бы грузить руками.
//
// Две ловушки, на которых спотыкаются чужие реализации, разобраны ниже:
// дырки внутри букв (О, Ф, 8) и слипание соседних букв из-за кернинга.

import { type IEdge, type IFace, type IShape, type IWire, type Plane, Result, type XYZ } from "@chili3d/core";
import type { Path } from "opentype.js/dist/opentype.mjs";
import type { LoadedFont } from "./fonts";

interface Точка {
    x: number;
    y: number;
}

type Отрезок =
    | { вид: "линия"; конец: Точка }
    /** Точки Безье без начальной: для квадратичной одна опорная, для кубической две. */
    | { вид: "безье"; точки: Точка[] };

interface Контур {
    начало: Точка;
    отрезки: Отрезок[];
    /** Ломаная того же контура — только чтобы понять, кто в ком лежит. */
    ломаная: Точка[];
}

/** На сколько частей дробим кривую при построении ломаной. */
const ДРОБЛЕНИЕ = 8;

/**
 * Разложить путь одного знака на контуры.
 *
 * opentype.js отдаёт координаты в системе экрана (y растёт вниз), поэтому y
 * переворачивается: в мастерской буква должна стоять, а не висеть.
 */
export function контурыЗнака(path: Path, сдвиг: Точка, допуск: number): Контур[] {
    const контуры: Контур[] = [];
    let текущий: Контур | undefined;
    let перо: Точка = { x: 0, y: 0 };

    const вМир = (x: number, y: number): Точка => ({
        x: x - сдвиг.x,
        y: -y - сдвиг.y,
    });

    const закрыть = () => {
        if (!текущий) return;
        if (расстояние(перо, текущий.начало) > допуск) {
            текущий.отрезки.push({ вид: "линия", конец: текущий.начало });
            текущий.ломаная.push(текущий.начало);
        }
        if (текущий.отрезки.length >= 2) контуры.push(текущий);
        текущий = undefined;
    };

    for (const команда of path.commands) {
        switch (команда.type) {
            case "M": {
                закрыть();
                перо = вМир(команда.x!, команда.y!);
                текущий = { начало: перо, отрезки: [], ломаная: [перо] };
                break;
            }
            case "L": {
                if (!текущий) break;
                const конец = вМир(команда.x!, команда.y!);
                if (расстояние(перо, конец) > допуск) {
                    текущий.отрезки.push({ вид: "линия", конец });
                    текущий.ломаная.push(конец);
                    перо = конец;
                }
                break;
            }
            case "Q": {
                if (!текущий) break;
                const опора = вМир(команда.x1!, команда.y1!);
                const конец = вМир(команда.x!, команда.y!);
                if (расстояние(перо, конец) > допуск || расстояние(перо, опора) > допуск) {
                    текущий.отрезки.push({ вид: "безье", точки: [опора, конец] });
                    добавитьЛоманую(текущий.ломаная, [перо, опора, конец]);
                    перо = конец;
                }
                break;
            }
            case "C": {
                if (!текущий) break;
                const опора1 = вМир(команда.x1!, команда.y1!);
                const опора2 = вМир(команда.x2!, команда.y2!);
                const конец = вМир(команда.x!, команда.y!);
                if (расстояние(перо, конец) > допуск || расстояние(перо, опора1) > допуск) {
                    текущий.отрезки.push({ вид: "безье", точки: [опора1, опора2, конец] });
                    добавитьЛоманую(текущий.ломаная, [перо, опора1, опора2, конец]);
                    перо = конец;
                }
                break;
            }
            case "Z":
                закрыть();
                break;
        }
    }
    закрыть();

    return контуры;
}

/**
 * Разложить контуры одного знака на «внешний + его дырки».
 *
 * Направление обхода здесь не спрашиваем: у TrueType заливку задаёт обход,
 * у шрифтов с кривыми CFF — вложенность, и полагаться на первое — известный
 * способ получить залитую букву «О». Считаем вложенность: контур внутри
 * чётного числа других — внешний, внутри нечётного — дырка.
 */
export function сгруппировать(контуры: Контур[]): Контур[][] {
    const глубина = контуры.map((к, i) =>
        контуры.reduce(
            (счёт, другой, j) => (j !== i && внутри(к.ломаная[0], другой.ломаная) ? счёт + 1 : счёт),
            0,
        ),
    );

    const группы: Контур[][] = [];
    const индексВнешнего = new Map<number, number>();

    контуры.forEach((к, i) => {
        if (глубина[i] % 2 === 0) {
            индексВнешнего.set(i, группы.length);
            группы.push([к]);
        }
    });

    контуры.forEach((к, i) => {
        if (глубина[i] % 2 === 0) return;
        // Дырка принадлежит самому тесному из объемлющих контуров.
        let хозяин = -1;
        контуры.forEach((другой, j) => {
            if (j === i || глубина[j] % 2 !== 0) return;
            if (!внутри(к.ломаная[0], другой.ломаная)) return;
            if (хозяин === -1 || глубина[j] > глубина[хозяин]) хозяин = j;
        });
        const группа = индексВнешнего.get(хозяин);
        if (группа !== undefined) группы[группа].push(к);
    });

    return группы;
}

/**
 * Объёмная надпись на плоскости.
 *
 * Буквы строятся по одной и в конце объединяются: у рукописных шрифтов росчерк
 * соседней буквы налезает на предыдущую, и компаунд из таких тел ядро потом
 * не берёт в булеву операцию. Если объединение не удалось — отдаём компаунд:
 * пусть надпись будет неидеальной, но будет.
 */
export function textShape(
    шрифт: LoadedFont,
    текст: string,
    высотаБукв: number,
    толщина: number,
    плоскость: Plane,
): Result<IShape> {
    const грани = textFaces(шрифт, текст, высотаБукв, плоскость);
    if (!грани.isOk) return Result.err(грани.error);

    const вектор = плоскость.normal.multiply(толщина);
    const тела: IShape[] = [];
    for (const граниЗнака of грани.value) {
        const заготовка =
            граниЗнака.length === 1 ? Result.ok(граниЗнака[0] as IShape) : shapeFactory.combine(граниЗнака);
        if (!заготовка.isOk) continue;
        const тело = shapeFactory.prism(заготовка.value, вектор);
        if (тело.isOk) тела.push(тело.value);
    }
    грани.value.flat().forEach((г) => отпустить(г));

    if (тела.length === 0) return Result.err("Не удалось построить буквы");
    if (тела.length === 1) return Result.ok(тела[0]);

    const слитые = shapeFactory.booleanFuse([тела[0]], тела.slice(1), true);
    if (слитые.isOk) {
        тела.forEach((т) => отпустить(т));
        return слитые;
    }
    return shapeFactory.combine(тела) as Result<IShape>;
}

/** Грани надписи, сгруппированные по знакам. */
export function textFaces(
    шрифт: LoadedFont,
    текст: string,
    высотаБукв: number,
    плоскость: Plane,
): Result<IFace[][]> {
    if (текст.trim().length === 0) return Result.err("Пустой текст");
    if (высотаБукв <= 0) return Result.err("Высота букв должна быть больше нуля");

    // Ребёнок задаёт высоту буквы в миллиметрах, opentype.js — кегль.
    const кегль = высотаБукв / шрифт.capHeight;
    const рамка = шрифт.font.getPath(текст, 0, 0, кегль).getBoundingBox();
    const сдвиг: Точка = { x: (рамка.x1 + рамка.x2) / 2, y: -(рамка.y1 + рамка.y2) / 2 };
    const допуск = высотаБукв * 1e-5;

    const грани: IFace[][] = [];
    for (const путь of шрифт.font.getPaths(текст, 0, 0, кегль)) {
        const контуры = контурыЗнака(путь, сдвиг, допуск);
        if (контуры.length === 0) continue;

        const граниЗнака: IFace[] = [];
        for (const группа of сгруппировать(контуры)) {
            const провода = группа.map((к) => контурВПровод(к, плоскость));
            if (провода.some((п) => !п.isOk)) {
                провода.forEach((п) => п.isOk && отпустить(п.value));
                continue;
            }
            const грань = shapeFactory.face(провода.map((п) => п.value as IWire));
            провода.forEach((п) => п.isOk && отпустить(п.value));
            if (грань.isOk) граниЗнака.push(грань.value);
        }
        if (граниЗнака.length > 0) грани.push(граниЗнака);
    }

    if (грани.length === 0) return Result.err("В этом шрифте нет таких знаков");
    return Result.ok(грани);
}

function контурВПровод(контур: Контур, плоскость: Plane): Result<IWire> {
    const рёбра: IEdge[] = [];
    let перо = контур.начало;

    for (const отрезок of контур.отрезки) {
        const ребро =
            отрезок.вид === "линия"
                ? shapeFactory.line(вТрёхмерное(перо, плоскость), вТрёхмерное(отрезок.конец, плоскость))
                : shapeFactory.bezier([перо, ...отрезок.точки].map((т) => вТрёхмерное(т, плоскость)));
        if (!ребро.isOk) {
            рёбра.forEach((р) => отпустить(р));
            return Result.err(ребро.error);
        }
        рёбра.push(ребро.value);
        перо = отрезок.вид === "линия" ? отрезок.конец : отрезок.точки[отрезок.точки.length - 1];
    }

    const провод = shapeFactory.wire(рёбра);
    рёбра.forEach((р) => отпустить(р));
    return провод;
}

function вТрёхмерное(точка: Точка, плоскость: Plane): XYZ {
    return плоскость.origin.add(плоскость.xvec.multiply(точка.x)).add(плоскость.yvec.multiply(точка.y));
}

/** Промежуточные формы живут в wasm — их надо отпускать, иначе память течёт. */
function отпустить(форма: { dispose: () => void }) {
    try {
        форма.dispose();
    } catch {
        // Форма уже отпущена — ничего страшного.
    }
}

function расстояние(a: Точка, b: Точка): number {
    return Math.hypot(a.x - b.x, a.y - b.y);
}

function добавитьЛоманую(ломаная: Точка[], опорные: Точка[]) {
    for (let i = 1; i <= ДРОБЛЕНИЕ; i++) {
        ломаная.push(безье(опорные, i / ДРОБЛЕНИЕ));
    }
}

function безье(точки: Точка[], t: number): Точка {
    let текущие = точки;
    while (текущие.length > 1) {
        const следующие: Точка[] = [];
        for (let i = 0; i < текущие.length - 1; i++) {
            следующие.push({
                x: текущие[i].x + (текущие[i + 1].x - текущие[i].x) * t,
                y: текущие[i].y + (текущие[i + 1].y - текущие[i].y) * t,
            });
        }
        текущие = следующие;
    }
    return текущие[0];
}

/** Луч вправо: нечётное число пересечений — точка внутри. */
function внутри(точка: Точка, ломаная: Точка[]): boolean {
    let внутриЛи = false;
    for (let i = 0, j = ломаная.length - 1; i < ломаная.length; j = i++) {
        const a = ломаная[i];
        const b = ломаная[j];
        if (a.y > точка.y !== b.y > точка.y) {
            const x = ((b.x - a.x) * (точка.y - a.y)) / (b.y - a.y) + a.x;
            if (точка.x < x) внутриЛи = !внутриЛи;
        }
    }
    return внутриЛи;
}
