// Разбор контуров буквы — единственная часть надписи, которую можно проверить
// без ядра: геометрию дальше строит OCCT, а вот «где дырка, а где буква» и
// «куда смотрит игрек» решает наш код, и ошибиться здесь легче всего.

import { describe, expect, test } from "@rstest/core";
import { контурыЗнака, сгруппировать } from "../../src/text/textShape";

type Команда = { type: string; x?: number; y?: number; x1?: number; y1?: number };

/** Прямоугольник по часовой стрелке в системе opentype (y растёт вниз). */
function прямоугольник(x1: number, y1: number, x2: number, y2: number): Команда[] {
    return [
        { type: "M", x: x1, y: y1 },
        { type: "L", x: x2, y: y1 },
        { type: "L", x: x2, y: y2 },
        { type: "L", x: x1, y: y2 },
        { type: "Z" },
    ];
}

const путь = (commands: Команда[]) => ({ commands }) as any;
const БЕЗ_СДВИГА = { x: 0, y: 0 };

describe("контурыЗнака", () => {
    test("замкнутый прямоугольник даёт один контур из четырёх отрезков", () => {
        const контуры = контурыЗнака(путь(прямоугольник(0, 0, 100, 100)), БЕЗ_СДВИГА, 1e-4);

        expect(контуры).toHaveLength(1);
        expect(контуры[0].отрезки).toHaveLength(4);
        expect(контуры[0].отрезки.every((о) => о.вид === "линия")).toBe(true);
    });

    test("игрек переворачивается: в шрифте вниз, в мастерской вверх", () => {
        const контуры = контурыЗнака(путь(прямоугольник(0, 0, 100, 100)), БЕЗ_СДВИГА, 1e-4);

        const игреки = контуры[0].ломаная.map((т) => т.y);
        expect(Math.min(...игреки)).toBe(-100);
        expect(Math.max(...игреки)).toBeCloseTo(0);
    });

    test("сдвиг вычитается — надпись встаёт серединой в начало плоскости", () => {
        const контуры = контурыЗнака(путь(прямоугольник(0, 0, 100, 100)), { x: 50, y: -50 }, 1e-4);

        const иксы = контуры[0].ломаная.map((т) => т.x);
        const игреки = контуры[0].ломаная.map((т) => т.y);
        expect(Math.min(...иксы)).toBe(-50);
        expect(Math.max(...иксы)).toBe(50);
        expect(Math.min(...игреки)).toBe(-50);
        expect(Math.max(...игреки)).toBe(50);
    });

    test("кривая Безье превращается в один отрезок и в ломаную из многих точек", () => {
        const контуры = контурыЗнака(
            путь([
                { type: "M", x: 0, y: 0 },
                { type: "Q", x1: 50, y1: 100, x: 100, y: 0 },
                { type: "L", x: 0, y: 0 },
            ]),
            БЕЗ_СДВИГА,
            1e-4,
        );

        expect(контуры).toHaveLength(1);
        expect(контуры[0].отрезки[0].вид).toBe("безье");
        expect(контуры[0].ломаная.length).toBeGreaterThan(3);
    });

    test("вырожденный контур из одной точки отбрасывается", () => {
        const контуры = контурыЗнака(путь([{ type: "M", x: 10, y: 10 }, { type: "Z" }]), БЕЗ_СДВИГА, 1e-4);

        expect(контуры).toHaveLength(0);
    });
});

describe("сгруппировать", () => {
    test("буква с дыркой: внутренний контур попадает к внешнему", () => {
        const контуры = контурыЗнака(
            путь([...прямоугольник(0, 0, 100, 100), ...прямоугольник(20, 20, 80, 80)]),
            БЕЗ_СДВИГА,
            1e-4,
        );

        const группы = сгруппировать(контуры);

        expect(группы).toHaveLength(1);
        expect(группы[0]).toHaveLength(2);
    });

    test("две отдельные части знака остаются двумя гранями", () => {
        const контуры = контурыЗнака(
            путь([...прямоугольник(0, 0, 40, 40), ...прямоугольник(60, 0, 100, 40)]),
            БЕЗ_СДВИГА,
            1e-4,
        );

        const группы = сгруппировать(контуры);

        expect(группы).toHaveLength(2);
        expect(группы.every((г) => г.length === 1)).toBe(true);
    });

    test("островок внутри дырки — снова буква, а не дырка", () => {
        const контуры = контурыЗнака(
            путь([
                ...прямоугольник(0, 0, 100, 100),
                ...прямоугольник(10, 10, 90, 90),
                ...прямоугольник(30, 30, 70, 70),
            ]),
            БЕЗ_СДВИГА,
            1e-4,
        );

        const группы = сгруппировать(контуры);

        // Внешний с дыркой — одна грань, островок — вторая.
        expect(группы).toHaveLength(2);
        expect(группы.map((г) => г.length).sort()).toEqual([1, 2]);
    });
});
