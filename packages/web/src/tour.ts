// Форк «Макетки»: тур по мастерской моделей при первом входе (B-278).
//
// Пришёл на смену подсказке в углу (`FirstHint`, удалена этой же правкой): три карточки ни на что
// не показывали, и ребёнок читал их, не понимая, о каком месте экрана речь. Здесь
// каждый пузырь подсвечивает ровно то место, про которое говорит, — остальное окно
// на это время затемнено и не нажимается (так работает driver.js по умолчанию, и это
// нам на руку: промахнуться мимо подсвеченного нельзя).
//
// Библиотека driver.js пришла отдельным шагом поставки и проведена через гейты:
//   • пакет лежит в `dependencies` пакета `@chili3d/web`, а не в `devDependencies`, —
//     `scripts/third-party.mjs` читает именно эту секцию, и в перечне для реестровой
//     заявки driver.js обязан числиться «в браузере», а не инструментом сборки;
//   • вес библиотеки входит в бюджет первого экрана, который меряет
//     `scripts/precompress.mjs --check` по собранному `dist`.

import { type DriveStep, driver } from "driver.js";
// Свои стили библиотеки: без них пузырь рисуется голым текстом без рамки и кнопок.
// Все правила под своими именами (`.driver-popover`, `.driver-overlay` и подобные) —
// на вёрстку редактора они не влияют, пока тур не запущен.
import "driver.js/dist/driver.css";
// Наши поправки к пузырю: размер подписи и мишень кнопок под палец.
import "./tour.css";
import { FRAME_FONT } from "./errorBanner";

/**
 * Где живёт отметка «тур показан» у гостя.
 *
 * У всех остальных она живёт у учётной записи (инвариант И-7: компьютер в классе
 * общий, иначе первый ребёнок съедает подсказку у всех), и ставит её ручка
 * `POST /api/tour-seen`. Но у гостя в пробе учётной записи нет вовсе, а делить
 * компьютер ему не с кем: проба открывается с лендинга, а не на уроке.
 */
export const КЛЮЧ_ГОСТЯ = "maketka.tour.3d";

/** Гость уже проходил тур в этом браузере? */
export function гостьВиделТур(): boolean {
    try {
        return localStorage.getItem(КЛЮЧ_ГОСТЯ) === "1";
    } catch {
        // Приватное окно и запрет на хранилище: пусть лучше тур покажется
        // второй раз, чем мастерская не откроется из-за настройки браузера.
        return false;
    }
}

/** Запомнить, что гость тур уже видел. */
export function запомнитьТурГостя() {
    try {
        localStorage.setItem(КЛЮЧ_ГОСТЯ, "1");
    } catch {
        // То же самое: не записалось — тур придёт ещё раз, и это не беда.
    }
}

/**
 * Шаги тура.
 *
 * Слова — из того же словаря, что шпаргалка «?» (`frameBar.ts`, `HELP_LINES`):
 * «лента команд», «сцена», «части модели». Термин инженерный, а рядом — объяснение
 * обычными словами; сюсюкающих замен («домик», «полочка») здесь нет намеренно —
 * ребёнок уходит с урока, зная, как эти места называются на самом деле.
 *
 * В каждом пузыре ровно одна мысль: восьмилетний читает его между делом, а не
 * изучает. Четыре шага — это весь путь от «где взять фигуру» до «работа цела».
 */
export function шагиТура(гость: boolean): DriveStep[] {
    return [
        {
            // Группу ищем по ключу, а не по месту в ленте: порядок групп задаёт
            // профиль ленты (`builder/src/ribbon.ts`), а подпись — перевод.
            element: '[data-ribbon-group="ribbon.group.draw"]',
            popover: {
                title: "Лента команд",
                description: "Фигуры берут здесь: кубик, шар, цилиндр. Выбери, с чего начнёшь.",
                side: "bottom",
                align: "start",
            },
        },
        {
            element: "chili-viewport",
            popover: {
                title: "Сцена",
                description: "Поставь фигуру щелчком и растяни мышью до нужного размера.",
                side: "left",
                align: "center",
            },
        },
        {
            element: "#editor-sidebar",
            popover: {
                title: "Части модели",
                description: "Всё построенное попадает в этот список — оттуда фигуру можно поправить.",
                side: "right",
                align: "center",
            },
        },
        {
            element: "[data-frame-state]",
            popover: гость
                ? {
                      // Гостю про автосохранение врать нельзя: проба не сохраняется вовсе,
                      // и в полосе каркаса на этом самом месте так и написано.
                      title: "Это проба",
                      description:
                          "Проба не сохраняется, о том и написано. Свои работы появятся, когда заведёшь мастерскую.",
                      side: "bottom",
                      align: "start",
                  }
                : {
                      title: "Сохранение",
                      description: "Работа сохраняется сама — здесь видно, как идут дела.",
                      side: "bottom",
                      align: "start",
                  },
        },
    ];
}

export interface ОпцииТура {
    /** Гость в пробе: у него другая последняя подсказка и другое место для отметки. */
    гость: boolean;
    /** Тур закончился — неважно, дошли до конца или закрыли на втором шаге. */
    пройден: () => void;
}

/**
 * Собирает тур и сразу запускает его.
 *
 * Отметку ставим в `onDestroyStarted`. Через этот крючок тур уходит с экрана целиком:
 * и «Понятно» на последнем шаге, и крестик, и Esc, и щелчок мимо пузыря сходятся
 * в него. Уйти можно в любой момент, и второй раз тур не придёт: ребёнок, закрывший
 * его на втором шаге, сказал этим то же самое, что дошедший до конца.
 *
 * Почему не соседний `onDestroyed`, который выглядит уместнее по имени: библиотека
 * зовёт его только после того, как подсветка первого шага доехала до места (у неё
 * на это до 400 мс анимации). Ребёнок, ткнувший в крестик сразу, ушёл бы без отметки
 * и получил тот же тур в следующий раз. `onDestroyStarted` срабатывает всегда — но
 * взамен библиотека перекладывает на нас сам снос: позвали крючок — закрывать
 * тур обязаны мы. Рукоятку берём из аргументов крючка: своя переменная на этой
 * строке ещё не присвоена.
 */
export function завестиТур(опции: ОпцииТура) {
    // Пузырь берёт шрифт из своей переменной, иначе рисуется Helvetica: среди
    // русского интерфейса на системном шрифте это заметно чужая надпись.
    document.documentElement.style.setProperty("--driver-popover-font-family", FRAME_FONT);

    const тур = driver({
        steps: шагиТура(опции.гость),
        // Место пропало (перебрали ленту, свернули панель) — шаг пропускаем. Пузырь
        // без подсветки встал бы посреди экрана и показывал в пустоту.
        skipMissingElement: true,
        showProgress: true,
        progressText: "{{current}} из {{total}}",
        nextBtnText: "Дальше",
        prevBtnText: "Назад",
        doneBtnText: "Понятно",
        onDestroyStarted: (_место, _шаг, { driver: рукоятка }) => {
            // Сначала снимаем тур, потом отмечаем. Пока он висит, затемнение глушит
            // нажатия по всему окну: споткнись отметка — ребёнок остался бы в
            // мастерской, которая не отвечает.
            рукоятка.destroy();
            опции.пройден();
        },
    });
    тур.drive();
    return тур;
}
